import {describe,expect,it} from 'vitest';
import {existsSync,readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
describe('reproducible Vercel function bundles',()=>{
 it('keeps third-party npm code out of committed hosted entrypoints',()=>{
  const body=readFileSync(resolve(root,'api/live.js'),'utf8');
  expect(body).not.toMatch(/node_modules\/\.pnpm\/(?!@myrqyry\+chatbus@)/);
  expect(body).toMatch(/import\(["']youtube-chat-next["']\)/);
  expect(body).toMatch(/from ["']ws["']/);
  const pkg=JSON.parse(readFileSync(resolve(root,'package.json'),'utf8'));
  expect(pkg.dependencies['youtube-chat-next']).toBe('3.1.0');
 });
 it('provides bundled JS entrypoints for both hosted routes',()=>{
  for(const p of ['api/live.js','api/live/status.js']){
   const full=resolve(root,p);
   expect(existsSync(full)).toBe(true);
   const body=readFileSync(full,'utf8');
   expect(body).toContain('Generated by esbuild');
   expect(body).not.toMatch(/from ["']\.\.?\/server\//);
   expect(body).not.toMatch(/from ["']\.\/hub["']/);
  }
  expect(existsSync(resolve(root,'api/live.ts'))).toBe(false);
 });
});
