/** Deterministic Vercel Functions ESM bundles. Keep their TypeScript sources
 * in server/entries; never rely on Node resolving .ts or extensionless ESM.
 */
import {build} from 'esbuild';
import {readFileSync} from 'node:fs';
const pkg=JSON.parse(readFileSync(new URL('../package.json',import.meta.url),'utf8'));
// Bundle only first-party code. The deployment installs the original npm
// dependencies using the same lockfile as local users.
const external=Object.keys(pkg.dependencies).filter(name=>name!=='@myrqyry/chatbus');
const result=await build({
 entryPoints:[
  {in:'server/entries/live.ts',out:'live'},
  {in:'server/entries/status.ts',out:'live/status'},
 ],
 outdir:'api',
 platform:'node',
 target:'node24',
 format:'esm',
 bundle:true,
 packages:'bundle',
 external,
 metafile:true,
 write:false,
 minify:false,
 legalComments:'inline',
 logLevel:'warning',
 banner:{js:`/* Generated by esbuild from server/entries. Do not edit. */
import { createRequire as __createRequire } from "node:module";
const require = __createRequire(import.meta.url);`},
});

// Refuse to emit a generated source artifact that embeds third-party npm
// code, even if a future Chatbus revision adds a new package dependency.
const embedded=Object.keys(result.metafile.inputs).filter(path=>
 path.includes('node_modules/')&&!path.includes('/node_modules/@myrqyry/chatbus/'));
if(embedded.length)throw Error('Unexpected embedded dependency: '+embedded.join(', '));
const imports=Object.values(result.metafile.outputs).flatMap(output=>output.imports)
 .filter(item=>item.external&&!item.path.startsWith('node:'));
for(const item of imports){
 if(!external.some(name=>item.path===name||item.path.startsWith(name+'/')))
  throw Error('Undeclared external dependency: '+item.path);
}
const {mkdirSync,writeFileSync}=await import('node:fs');
const {dirname}=await import('node:path');
for(const file of result.outputFiles){
 mkdirSync(dirname(file.path),{recursive:true});
 writeFileSync(file.path,file.contents);
}
console.log('Hosted entrypoints: first-party code only; npm dependencies external');
